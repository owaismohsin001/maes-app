const translations = { en, nl };

export type Locale = keyof typeof translations;

/** Device language, reduced to a supported locale. Hermes ships `Intl` on both platforms. */
export function getLocale(): Locale {
  try {
    const tag = Intl.DateTimeFormat().resolvedOptions().locale ?? '';
    return tag.toLowerCase().startsWith('nl') ? 'nl' : 'en';
  } catch {
    return 'en';
  }
}

export function t(key: TranslationKey, locale: Locale = getLocale()): string {
  return translations[locale][key] ?? en[key];
}
