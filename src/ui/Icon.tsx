export type IconName = keyof typeof GLYPHS;

type Props = {
  name: IconName;
  size?: number;
  color: string;
  strokeWidth?: number;
};

function Icon({ name, size = 24, color, strokeWidth = 2 }: Props) {
  const glyph: Shape[] | FaGlyph = GLYPHS[name];
  if (!Array.isArray(glyph)) {
    // Centred in a square box; flipped because font units count y upwards.
    const { w, d } = glyph.fa;
    const box = Math.max(w, FA_EM);
    return (
      <Svg
        width={size}
        height={size}
        viewBox={`${(w - box) / 2} ${
          -FA_ASCENT - (box - FA_EM) / 2
        } ${box} ${box}`}
      >
        <G transform="scale(1,-1)">
          <Path d={d} fill={color} />
        </G>
      </Svg>
    );
  }
  const shapes = glyph;
  return (
    <Svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {shapes.map((shape, i) =>
        typeof shape === 'string' ? (
          <Path key={i} d={shape} />
        ) : 'circle' in shape ? (
          <Circle
            key={i}
            cx={shape.circle[0]}
            cy={shape.circle[1]}
            r={shape.circle[2]}
          />
        ) : (
          <Rect
            key={i}
            x={shape.rect[0]}
            y={shape.rect[1]}
            width={shape.rect[2]}
            height={shape.rect[3]}
            rx={shape.rect[4]}
          />
        ),
      )}
    </Svg>
  );
}

